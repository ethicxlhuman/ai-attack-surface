#!/usr/bin/env python3
"""Build the layer pages and TIMELINE.md from data/attack-surface.json.

Usage:
  python3 scripts/build.py          # write the generated pages
  python3 scripts/build.py --check  # fail if data is invalid or pages are stale
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "attack-surface.json"
EVIDENCE = {"WILD", "CVE", "PoC", "THEORY"}
DATE = re.compile(r"^\d{4}(-\d{2}(-\d{2})?)?$")
GEN = "<!-- Generated by scripts/build.py from data/attack-surface.json. Edit the data, not this file. -->"


def validate(d):
    errs, layers = [], {l["id"] for l in d["layers"]}
    seen = set()
    for t in d["techniques"]:
        tid = t["id"]
        if tid in seen: errs.append(f"{tid}: duplicate id")
        seen.add(tid)
        if t["layer"] not in layers: errs.append(f"{tid}: unknown layer")
        if not tid.startswith(t["layer"] + "."): errs.append(f"{tid}: id does not match layer")
        if t["evidence"] not in EVIDENCE: errs.append(f"{tid}: bad evidence {t['evidence']}")
        ev = t["events"]
        if not ev: errs.append(f"{tid}: no events")
        if sum(1 for e in ev if e.get("first")) != 1: errs.append(f"{tid}: needs exactly one 'first' event")
        for e in ev:
            if not DATE.match(e["date"]): errs.append(f"{tid}: bad date {e['date']}")
            if not e["url"].startswith("http"): errs.append(f"{tid}: bad url")
            if "youtube.com" in e["url"] or "youtu.be" in e["url"]: errs.append(f"{tid}: video is not a primary source")
        dates = [e["date"] for e in ev]
        if dates != sorted(dates, reverse=True): errs.append(f"{tid}: events not newest-first")
        if ev and not ev[-1].get("first"): errs.append(f"{tid}: 'first' event must be the oldest")
    return errs


def latest(t):
    return max(e["date"] for e in t["events"])


def first(t):
    return next(e for e in t["events"] if e.get("first"))


def layer_page(d, L):
    ts = sorted((t for t in d["techniques"] if t["layer"] == L["id"]), key=latest, reverse=True)
    out = [GEN, "", f"# {L['id']} · {L['name']}", "", f"**{L['question']}**", "", L["plain"], "",
           f"*Example:* {L['example']}", "", f"Last updated {d['updated']} · {len(ts)} techniques · newest activity first.", "",
           "| ID | Technique | Evidence | First described | Latest |", "|---|---|---|---|---|"]
    for t in ts:
        f = first(t)
        out.append(f"| [{t['id']}](#{t['id'].lower().replace('.', '')}) | {t['name']} | {t['evidence']} | {f['date']} · [{f['source']}]({f['url']}) | {latest(t)} |")
    for t in ts:
        f = first(t)
        out += ["", f"## {t['id']}", "", f"### {t['name']}", "",
                f"**Evidence:** {t['evidence']} · **First described:** {f['date']}, {f['source']}", "", t["summary"], "",
                "| Date | What happened | Source |", "|---|---|---|"]
        for e in t["events"]:
            tag = " **(first)**" if e.get("first") else ""
            out.append(f"| {e['date']} | {e['what']}{tag} | [{e['source']}]({e['url']}) |")
    out += ["", "[Back to the map](../README.md) · [Full timeline](../TIMELINE.md)", ""]
    return "\n".join(out)


def timeline(d):
    names = {l["id"]: l["name"] for l in d["layers"]}
    rows = []
    for t in d["techniques"]:
        for e in t["events"]:
            rows.append((e["date"], t, e))
    rows.sort(key=lambda r: (r[0], r[1]["id"]), reverse=True)
    out = [GEN, "", "# Timeline", "", f"Every dated event in the repository, newest first. Last updated {d['updated']}.", "",
           "| Date | Layer | Technique | What happened | Source |", "|---|---|---|---|---|"]
    for date, t, e in rows:
        slug = next(l["slug"] for l in d["layers"] if l["id"] == t["layer"])
        tag = " **(first)**" if e.get("first") else ""
        out.append(f"| {date} | {t['layer']} {names[t['layer']]} | [{t['id']}](layers/{slug}.md#{t['id'].lower().replace('.', '')}) {t['name']} | {e['what']}{tag} | [{e['source']}]({e['url']}) |")
    return "\n".join(out) + "\n"


def main():
    d = json.loads(DATA.read_text())
    errs = validate(d)
    if errs:
        print("\n".join(errs)); sys.exit(1)
    pages = {ROOT / "TIMELINE.md": timeline(d)}
    for L in d["layers"]:
        pages[ROOT / "layers" / f"{L['slug']}.md"] = layer_page(d, L)
    check = "--check" in sys.argv
    stale = []
    for p, text in pages.items():
        if check:
            if not p.exists() or p.read_text() != text: stale.append(str(p.relative_to(ROOT)))
        else:
            p.parent.mkdir(parents=True, exist_ok=True); p.write_text(text)
    if stale:
        print("Stale, run scripts/build.py:", *stale, sep="\n  "); sys.exit(1)
    n = len(d["techniques"]); e = sum(len(t["events"]) for t in d["techniques"])
    print(f"{'ok' if check else 'built'}: {len(d['layers'])} layers, {n} techniques, {e} events")


if __name__ == "__main__":
    main()
